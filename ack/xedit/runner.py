"""Run an xEdit script unattended.

1. Render a script template (target plugin + output folder) into xEdit's Edit Scripts folder.
2. Write a plugin list so xEdit loads exactly the target and its masters (-P:), never the user's plugins.txt.
3. Launch xEdit with -autoload -script -autoexit and watch its windows with an allowlist DialogWatcher.
4. When the script writes DONE.txt, close xEdit; in save runs, the allowlist handles the save prompt.
5. Return a report: outcome, dialogs acted on, unknown dialogs captured (with screenshots), output files.

A run never clicks anything that isn't in rules.json. If an unknown dialog blocks progress, the run times
out, xEdit is terminated (unsaved), and the captured dialog is in the report for review.
"""
from __future__ import annotations

import json
import shutil
import subprocess
import time
from dataclasses import asdict, dataclass, field
from datetime import datetime
from pathlib import Path

from .. import config as cfg_mod
from .. import win32
from .dialogs import DialogWatcher

SCRIPTS = Path(__file__).with_name('scripts')
OFFICIAL_MASTERS = ['Fallout4.esm', 'DLCRobot.esm', 'DLCworkshop01.esm', 'DLCCoast.esm',
                    'DLCworkshop02.esm', 'DLCworkshop03.esm', 'DLCNukaWorld.esm']


@dataclass
class RunReport:
    script: str
    target: str
    save: bool
    out_dir: str
    outcome: str = 'pending'        # done | timeout | crashed
    seconds: float = 0.0
    exit_code: int | None = None
    events: list = field(default_factory=list)
    unknown_dialogs: list = field(default_factory=list)
    outputs: list = field(default_factory=list)

    def summary(self) -> str:
        lines = [f'{self.script} on {self.target}: {self.outcome} in {self.seconds:.0f}s (save={self.save})']
        for e in self.events:
            lines.append(f'  [{e["kind"]}] {e["title"]!r} ({e["cls"]}) {e["rule"] or ""} {e["detail"]}')
        if self.unknown_dialogs:
            lines.append(f'  {len(self.unknown_dialogs)} unknown dialog(s) captured in {self.out_dir} - review and add rules')
        lines.append(f'  outputs: {", ".join(self.outputs) or "none"}')
        return '\n'.join(lines)


def _plugin_list(masters: list[str], target: str) -> str:
    lines = ['# Generated by AgentCreationKit for one xEdit run']
    lines += ['*' + m for m in masters] + ['*' + target]
    return '\n'.join(lines) + '\n'


def run(script: str, target: str, *, save: bool = False, masters: list[str] | None = None,
        timeout: float = 900, cfg: cfg_mod.Config | None = None) -> RunReport:
    cfg = cfg or cfg_mod.load()
    stamp = datetime.now().strftime('%Y%m%d-%H%M%S')
    out = (cfg.work_dir / f'{stamp}-{script}').resolve()
    out.mkdir(parents=True, exist_ok=True)
    out_str = str(out) + '\\'

    # 1. script
    template = (SCRIPTS / f'{script}.pas').read_text(encoding='utf8')
    if "'" in target or "'" in out_str:
        raise ValueError('Paths containing quotes are not supported in Pascal string constants')
    rendered = template.replace('{{TARGET}}', target).replace('{{OUT}}', out_str)
    script_name = f'ACK_{script}.pas'
    (cfg.xedit_scripts_dir / script_name).write_text(rendered, encoding='utf8')

    # 2. plugin list
    plugins = out / 'plugins.txt'
    plugins.write_text(_plugin_list(masters or OFFICIAL_MASTERS, target), encoding='utf8')

    report = RunReport(script, target, save, str(out))
    args = [str(cfg.xedit_exe), '-IKnowWhatImDoing', f'-P:{plugins}', '-autoload', f'-script:{script_name}', '-autoexit']
    (out / 'command.txt').write_text(subprocess.list2cmdline(args), encoding='utf8')

    # 3. launch + watch
    t0 = time.time()
    proc = subprocess.Popen(args, cwd=str(cfg.xedit_exe.parent))
    watcher = DialogWatcher(proc.pid, out, save)
    done_file = out / 'DONE.txt'
    close_sent = False
    try:
        while proc.poll() is None:
            watcher.poll()
            if done_file.exists() and not close_sent:
                time.sleep(1.0)  # let xEdit finish writing / return from the script
                if watcher.main_hwnd:
                    win32.close(watcher.main_hwnd)  # graceful: lets the allowlist answer any save prompt
                elif not save:
                    proc.kill()  # read-only run: nothing to save, main window not identified
                close_sent = True
            if time.time() - t0 > timeout:
                report.outcome = 'timeout'
                break
            time.sleep(0.4)
    finally:
        if proc.poll() is None:
            proc.kill()
            proc.wait(10)
    report.seconds = time.time() - t0
    report.exit_code = proc.returncode
    if report.outcome == 'pending':
        report.outcome = 'done' if done_file.exists() else 'crashed'
    report.events = [asdict(e) for e in watcher.events]
    report.unknown_dialogs = [asdict(e) for e in watcher.unknown]
    report.outputs = sorted(p.name for p in out.iterdir() if p.suffix in ('.txt',) and p.name not in ('plugins.txt', 'command.txt'))
    (out / 'report.json').write_text(json.dumps(asdict(report), indent=1), encoding='utf8')
    return report
