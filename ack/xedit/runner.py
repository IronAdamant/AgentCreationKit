"""Run an xEdit script unattended.

1. Render a script template (target plugin + output folder) into xEdit's Edit Scripts folder.
2. Write a plugin list so xEdit loads exactly the target and its masters (-P:), never the user's plugins.txt.
3. Launch xEdit with -autoload -script -autoexit and watch its windows with an allowlist DialogWatcher.
4. When the script writes DONE.txt: save runs close xEdit normally, which makes it save changed plugins
   (in script mode it does so without asking, keeping a copy in Data/FO4Edit Backups); read-only runs
   terminate it, which can never write anything.
5. Return a report: outcome, dialogs acted on, unknown dialogs captured (with screenshots), output files.

A run never clicks anything that isn't in rules.json. If an unknown dialog blocks progress, the run times
out, xEdit is terminated (nothing saved), and the captured dialog is in the report for review.

With "mo2" in config.local.json, xEdit is started through Mod Organizer 2 so it sees the profile's mods (ack/mo2.py);
the run then follows xEdit's own process, not MO2's.
"""
from __future__ import annotations

import json
import re
import shutil
import subprocess
import time
from dataclasses import asdict, dataclass, field
from datetime import datetime
from pathlib import Path

from .. import config as cfg_mod
from .. import win32
from .dialogs import DialogWatcher

SCRIPTS = Path(__file__).with_name('scripts')


class Refused(RuntimeError):
    """The run was not started because it could not be done safely."""


@dataclass
class RunReport:
    script: str
    target: str
    save: bool
    out_dir: str
    outcome: str = 'pending'        # done | script_error | save_error | timeout | crashed | not_started
    seconds: float = 0.0
    exit_code: int | None = None
    events: list = field(default_factory=list)
    unknown_dialogs: list = field(default_factory=list)
    outputs: list = field(default_factory=list)
    saved_to: str = ''              # save runs: where the target plugin is now (under MO2: which mod, or overwrite)

    def summary(self) -> str:
        lines = [f'{self.script} on {self.target}: {self.outcome} in {self.seconds:.0f}s (save={self.save})']
        for e in self.events:
            lines.append(f'  [{e["kind"]}] {e["title"]!r} ({e["cls"]}) {e["rule"] or ""} {e["detail"]}')
        if self.unknown_dialogs:
            lines.append(f'  {len(self.unknown_dialogs)} unknown dialog(s) captured in {self.out_dir} - review and add rules')
        lines.append(f'  outputs: {", ".join(self.outputs) or "none"}')
        if self.saved_to:
            lines.append(f'  plugin: {self.saved_to}')
        if self.outcome == 'not_started':
            lines.append('  xEdit did not start: through MO2, check that MO2 opens this instance and profile '
                         '(python -m ack doctor), and look for a message from MO2 on screen')
        if self.outcome in ('script_error', 'save_error'):
            log = Path(self.out_dir) / 'xedit_log.txt'
            lines += ['  xEdit log (end):'] + ['    ' + l for l in log.read_text(encoding='utf8').splitlines()[-4:]]
        return '\n'.join(lines)


def messages_text(main_hwnd: int) -> str:
    """Text of xEdit's Messages pane (a TMemo on the main window)."""
    memos = [c for c in win32.child_controls(main_hwnd) if c.cls == 'TMemo']
    return max((win32.control_text(m.hwnd) for m in memos), key=len, default='')


def _plugin_list(masters: list[str], target: str, after: list[str] | None = None) -> str:
    lines = ['# Generated by AgentCreationKit for one xEdit run']
    lines += ['*' + m for m in masters] + ['*' + target] + ['*' + a for a in (after or [])]
    return '\n'.join(lines) + '\n'


class _Process:
    """xEdit's process: the one ack started, or (through MO2) one found by its exe name."""

    def __init__(self, popen: subprocess.Popen | None = None, pid: int | None = None):
        self.popen, self.pid = popen, popen.pid if popen else pid

    def poll(self):
        if self.popen:
            return self.popen.poll()
        return None if win32.process_alive(self.pid) else -1

    def kill(self):
        if self.popen:
            self.popen.kill()
            self.popen.wait(10)
        else:
            win32.kill(self.pid)

    @property
    def returncode(self):
        return self.popen.returncode if self.popen else None


def _started_by_mo2(exe_name: str, before: set[int], timeout: float) -> _Process | None:
    """The xEdit MO2 starts: a new process with xEdit's exe name. MO2 may hand the command to an MO2 that is
    already open and exit at once, so its own process says nothing."""
    end = time.time() + timeout
    while time.time() < end:
        new = [p for p in win32.pids_of(exe_name) if p not in before]
        if new:
            return _Process(pid=new[0])
        time.sleep(0.5)
    return None


def _where(cfg: cfg_mod.Config, target: str) -> str:
    if not cfg.mo2:
        return str(cfg.data_path(target))
    found = cfg.mo2.origin(target)
    if not found:
        return 'not found'
    where, path = found
    note = ' - MO2 overwrite: move it into its mod folder' if where == 'overwrite' else ''
    return f'{path} ({where}){note}'


def run(script: str, target: str, *, save: bool = False, masters: list[str] | None = None,
        timeout: float = 900, params: dict[str, str] | None = None, also_load: list[str] | None = None,
        cfg: cfg_mod.Config | None = None) -> RunReport:
    """also_load: extra plugins loaded after the target (e.g. add-ons that use the target as a master).
    masters: plugins loaded before the target (default: the game's official masters)."""
    cfg = cfg or cfg_mod.load()
    if save:
        from ..ck.lifecycle import save_blocker
        blocker = save_blocker([target] + list(also_load or []), cfg)
        if blocker:
            raise Refused(blocker)
    stamp = datetime.now().strftime('%Y%m%d-%H%M%S')
    # A bundled script name, or a path to a project's own .pas template (e.g. kept in the mod's repo).
    script_path = Path(script) if script.lower().endswith('.pas') else SCRIPTS / f'{script}.pas'
    script = script_path.stem
    out = (cfg.work_dir / f'{stamp}-{script}').resolve()
    out.mkdir(parents=True, exist_ok=True)
    out_str = str(out) + '\\'

    # 1. script
    template = script_path.read_text(encoding='utf8')
    if "'" in target or "'" in out_str:
        raise ValueError('Paths containing quotes are not supported in Pascal string constants')
    rendered = template.replace('{{TARGET}}', target).replace('{{OUT}}', out_str)
    for key, value in (params or {}).items():
        if "'" in value:
            raise ValueError(f'parameter {key} contains a quote')
        rendered = rendered.replace('{{' + key + '}}', value)
    missing = sorted(set(re.findall(r'\{\{(\w+)\}\}', rendered)))
    if missing:
        raise ValueError(f'script {script_path.name} needs --param for: {", ".join(missing)}')
    script_name = f'ACK_{script}.pas'
    (cfg.xedit_scripts_dir / script_name).write_text(rendered, encoding='utf8')

    # 2. plugin list
    plugins = out / 'plugins.txt'
    plugins.write_text(_plugin_list(masters or list(cfg.game.masters), target, also_load), encoding='utf8')

    report = RunReport(script, target, save, str(out))
    args = ['-IKnowWhatImDoing', f'-P:{plugins}', '-autoload', f'-script:{script_name}', '-autoexit']
    if cfg.xedit_exe.name.lower() != cfg.game.xedit_exe.lower():
        args.insert(0, cfg.game.xedit_mode)  # a generic xEdit.exe picks the game from its name otherwise
    command = cfg.command(cfg.xedit_exe, args, cfg.xedit_exe.parent)
    (out / 'command.txt').write_text(subprocess.list2cmdline(command), encoding='utf8')

    # 3. launch + watch
    t0 = time.time()
    before = set(win32.pids_of(cfg.xedit_exe.name)) if cfg.mo2 else set()
    launcher = subprocess.Popen(command, cwd=str(cfg.xedit_exe.parent))
    proc = _Process(launcher) if not cfg.mo2 else _started_by_mo2(cfg.xedit_exe.name, before, timeout=120)
    if proc is None:
        report.outcome, report.seconds = 'not_started', time.time() - t0
        (out / 'report.json').write_text(json.dumps(asdict(report), indent=1), encoding='utf8')
        return report
    watcher = DialogWatcher(proc.pid, out, save)
    done_file = out / 'DONE.txt'
    close_sent = False
    next_log_check = 0.0
    try:
        while proc.poll() is None:
            watcher.poll()
            # A script error only shows up in xEdit's Messages pane: read it so the run fails at once
            # instead of waiting for the timeout.
            # A plugin that cannot be written shows up there too, after the close, and xEdit then just sits.
            if watcher.main_hwnd and (not done_file.exists() or close_sent) and time.time() > next_log_check:
                next_log_check = time.time() + 2.0
                log = messages_text(watcher.main_hwnd)
                failure = ('script_error' if 'Aborted: Applying script' in log
                           else 'save_error' if 'Error saving' in log else None)
                if failure:
                    report.outcome = failure
                    (out / 'xedit_log.txt').write_text('\n'.join(log.splitlines()[-40:]), encoding='utf8')
                    break
            if done_file.exists() and not close_sent:
                time.sleep(1.0)  # let xEdit finish writing / return from the script
                if not save:
                    # xEdit in script mode saves changed plugins automatically on a normal close, with no
                    # prompt. Terminating is the only way to guarantee a read-only run writes nothing.
                    proc.kill()
                elif watcher.main_hwnd:
                    win32.close(watcher.main_hwnd)  # normal close: xEdit saves the changed plugins
                close_sent = True
            if time.time() - t0 > timeout:
                report.outcome = 'timeout'
                # Script errors appear only in xEdit's Messages pane, not as dialogs: keep a picture of it.
                if watcher.main_hwnd:
                    shot = win32.screenshot_bmp(watcher.main_hwnd)
                    if shot:
                        (out / 'timeout_main_window.bmp').write_bytes(shot)
                break
            time.sleep(0.4)
    finally:
        if proc.poll() is None:
            proc.kill()
    report.seconds = time.time() - t0
    report.exit_code = proc.returncode
    if report.outcome == 'pending':
        report.outcome = 'done' if done_file.exists() else 'crashed'
    report.events = [asdict(e) for e in watcher.events]
    report.unknown_dialogs = [asdict(e) for e in watcher.unknown]
    if save:
        report.saved_to = _where(cfg, target)
    report.outputs = sorted(p.name for p in out.iterdir() if p.suffix in ('.txt',) and p.name not in ('plugins.txt', 'command.txt'))
    (out / 'report.json').write_text(json.dumps(asdict(report), indent=1), encoding='utf8')
    return report
